"""Generate the Webots world, point the controller at this Python, and run the drive.

usage (from the workshop folder):
  python webots_demo/run_webots.py                       # headless sweep over all lighting conditions -> webots_demo/sim_results/
  python webots_demo/run_webots.py --gui                  # open the Webots window and watch the drive
  python webots_demo/run_webots.py --conditions noon night --video demo.mp4

The car is a camera on a "supervisor" robot that moves itself along a straight road (no vehicle physics needed).
Because the simulator knows where every sign is, each frame gives the TRUE distance to compare with the pinhole estimate.
"""
import argparse, json, os, shutil, subprocess, sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
GH = "https://raw.githubusercontent.com/cyberbotics/webots/R2025a/projects/objects"
TEX = f"{GH}/traffic/protos/textures/signs"

# family = our class name, or None for a decoy (a real sign that is NOT one of our 6 classes -> any detection on it is wrong)
# kind: proto used; h = real panel height (m) used by the pinhole estimate; w = panel width; dz = panel centre offset
SIGNS = [
    ("Stop",           "StopSign",  "stop.jpg"),
    (None,             "OrderSign", "eu/speed_limit_70.jpg"),
    ("Speed Limit 30", "OrderSign", "eu/speed_limit_30.jpg"),
    ("Give Way",       "YieldSign", "eu/yield.jpg"),
    (None,             "OrderSign", "eu/speed_limit_20.jpg"),
    ("No Entry",       "OrderSign", "do_not_enter_without_text.jpg"),
    ("Speed Limit 50", "OrderSign", "eu/speed_limit_50.jpg"),
    (None,             "OrderSign", "eu/turn_left.jpg"),
    ("Keep Right",     "OrderSign", "eu/pass_right.jpg"),
]
GEOM = {"StopSign": dict(h=0.634, w=0.634, dz=0.0), "YieldSign": dict(h=0.743, w=0.84, dz=-0.10), "OrderSign": dict(h=0.66, w=0.66, dz=0.0)}
PANEL = {"StopSign": "StopPanel", "YieldSign": "YieldPanel", "OrderSign": "OrderPanel"}
FIRST_X, SPACING, SIGN_Y, LANE_Y, CAM_Z = 50.0, 50.0, -5.4, -1.75, 1.4


def world_text():
    ext = [f"{GH}/road/protos/StraightRoadSegment.proto"] + [f"{GH}/traffic/protos/{k}.proto" for k in sorted({s[1] for s in SIGNS})]
    ext += [f"{GH}/traffic/protos/{p}.proto" for p in sorted({PANEL[s[1]] for s in SIGNS})]
    length = FIRST_X + SPACING * len(SIGNS) + 40
    out = ["#VRML_SIM R2025a utf8", ""] + [f'EXTERNPROTO "{u}"' for u in ext] + ["", f"""WorldInfo {{
  info [ "Traffic-sign drive with ground-truth distance (generated by run_webots.py)" ]
  basicTimeStep 32
}}
Viewpoint {{
  orientation 0 1 0 0.2
  position -12 {LANE_Y + 1} 4.5
  follow "CAR"
}}
DEF SKY Background {{
  skyColor [ 0.62 0.76 0.92 ]
  luminosity 1
}}
DEF SUN DirectionalLight {{
  direction -0.4 0.3 -1
  intensity 1.6
  castShadows TRUE
}}
DEF AMBIENT DirectionalLight {{
  direction 0.3 -0.2 -1
  intensity 0.5
}}
DEF FOG Fog {{
  color 0.75 0.78 0.8
  visibilityRange 0
}}
DEF GROUND Solid {{
  translation {length / 2 - 20} 0 -0.02
  children [ Shape {{ appearance PBRAppearance {{ baseColor 0.32 0.42 0.22 roughness 1 metalness 0 }} geometry Plane {{ size {length + 200} 300 }} }} ]
  name "ground"
}}
StraightRoadSegment {{
  translation -20 0 0.01
  name "road"
  width 7
  length {length}
}}"""]
    # a few plain buildings for background clutter (built-in shapes, no download)
    for i, x in enumerate(range(30, int(length), 37)):
        side = -1 if i % 2 else 1
        h = 6 + (i * 7) % 9
        col = [(0.62, 0.55, 0.5), (0.7, 0.7, 0.68), (0.55, 0.5, 0.6)][i % 3]
        out.append(f"""Solid {{
  translation {x} {side * (14 + (i * 5) % 8)} {h / 2}
  children [ Shape {{ appearance PBRAppearance {{ baseColor {col[0]} {col[1]} {col[2]} roughness 0.9 metalness 0 }} geometry Box {{ size 10 8 {h} }} }} ]
  name "building {i}"
}}""")
    for i, (fam, kind, tex) in enumerate(SIGNS):
        x = FIRST_X + SPACING * i
        out.append(f"""DEF SIGN_{i} {kind} {{
  translation {x} {SIGN_Y} 0
  rotation 0 0 1 3.14159
  name "sign {i}"
  signBoards [ {PANEL[kind]} {{ {'translation 0.026 0 -0.175 ' if kind == 'OrderSign' else ('translation 0 0 -0.097 ' if kind == 'StopSign' else '')}signImage [ "{TEX}/{tex}" ] }} ]
}}""")
    out.append(f"""DEF CAR Robot {{
  translation 0 {LANE_Y} {CAM_Z}
  children [
    Camera {{
      name "camera"
      width 1280
      height 720
      fieldOfView 1.0
      antiAliasing TRUE
    }}
    Display {{
      name "detector_view"
      width 768
      height 432
    }}
    DEF HEADLIGHT SpotLight {{
      attenuation 0 0 0.02
      beamWidth 0.5
      cutOffAngle 0.75
      direction 1 0 -0.12
      intensity 6
      location 0.5 0 -0.6
      radius 120
      on FALSE
    }}
  ]
  name "CAR"
  controller "sign_drive"
  supervisor TRUE
}}
""")
    return "\n".join(out)


def find_webots():
    for p in [os.environ.get("WEBOTS_HOME", ""), os.path.expandvars(r"%LOCALAPPDATA%\Programs\Webots"), r"C:\Program Files\Webots", "/usr/local/webots", "/Applications/Webots.app"]:
        for exe in ["msys64/mingw64/bin/webots.exe", "webots", "Contents/MacOS/webots"]:
            if p and (Path(p) / exe).exists():
                return Path(p) / exe
    return shutil.which("webots")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--weights", default=str(ROOT / "models" / "signs6_y11s_fixed.pt"))
    ap.add_argument("--conditions", nargs="+", default=["noon", "overcast", "dusk", "night", "fog", "dense_fog"])
    ap.add_argument("--video", default=None, help="annotated video (in the output folder); default demo_hd.mp4 headless, none with --gui; '' = none")
    ap.add_argument("--video-conditions", nargs="+", default=["noon", "dusk", "night", "fog"])
    ap.add_argument("--conf", type=float, default=0.4)
    ap.add_argument("--imgsz", type=int, default=640)
    ap.add_argument("--step-m", type=float, default=0.5, help="metres driven per frame")
    ap.add_argument("--out", default=None, help="default sim_results/ (headless) or sim_results_gui/ (--gui), so watching never overwrites the measurement")
    ap.add_argument("--gui", action="store_true", help="show the Webots window (real-time) instead of a fast headless run")
    ap.add_argument("--quit", action="store_true", help="close Webots at the end of the drive (also in --gui mode)")
    a = ap.parse_args()
    a.out = a.out or str(HERE / ("sim_results_gui" if a.gui else "sim_results"))
    a.video = ("" if a.gui else "demo_hd.mp4") if a.video is None else a.video

    world = HERE / "worlds" / "sign_drive.wbt"
    world.parent.mkdir(exist_ok=True); world.write_text(world_text(), encoding="utf8")
    ctrl = HERE / "controllers" / "sign_drive"
    cfg = dict(weights=a.weights, conditions=a.conditions, video=a.video, video_conditions=a.video_conditions, conf=a.conf, imgsz=a.imgsz,
               step_m=a.step_m, out=a.out, signs=[dict(id=i, family=f, kind=k, image=t, **GEOM[k]) for i, (f, k, t) in enumerate(SIGNS)],
               spacing=SPACING, first_x=FIRST_X, quit_at_end=(not a.gui) or a.quit, show=a.gui)
    (ctrl / "run_config.json").write_text(json.dumps(cfg, indent=1))
    (ctrl / "runtime.ini").write_text(f"[python]\nCOMMAND = {sys.executable}\n")   # run the controller with THIS Python (has torch + ultralytics)
    exe = find_webots()
    if not exe:
        sys.exit("Webots not found: install it (cyberbotics.com) or set WEBOTS_HOME")
    args = [str(exe), "--stdout", "--stderr"] + ([] if a.gui else ["--batch", "--mode=fast", "--minimize", "--no-rendering"]) + [str(world)]
    print("running:", " ".join(args))
    rc = subprocess.call(args)
    hd = Path(a.out) / a.video if a.video else None
    if hd and hd.exists() and not a.gui:     # small copy for sharing: 960x540, 15 fps (~30 MB instead of ~160 MB)
        import cv2
        cap = cv2.VideoCapture(str(hd)); small = hd.with_name(hd.stem.replace("_hd", "") + ("" if "_hd" in hd.stem else "_small") + ".mp4")
        w = cv2.VideoWriter(str(small), cv2.VideoWriter_fourcc(*"mp4v"), 15, (960, 540)); i = 0
        while True:
            ok, im = cap.read()
            if not ok:
                break
            if i % 2 == 0:
                w.write(cv2.resize(im, (960, 540), interpolation=cv2.INTER_AREA))
            i += 1
        w.release(); print("small video:", small)
    sys.exit(rc)


if __name__ == "__main__":
    main()
